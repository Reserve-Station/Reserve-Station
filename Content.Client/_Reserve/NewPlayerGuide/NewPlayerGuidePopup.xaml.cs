namespace Content.Client._Reserve.NewPlayerGuide;

[GenerateTypedNameReferences]
public sealed partial class NewPlayerGuidePopup : Control
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;

    private readonly List<Control> _pages = new();
    private readonly SpeechPreviewControl _speechPreview = new();

    private Control? _slidersCard;
    private Control? _bubblesCard;

    private int _pageIndex;

    private bool _showRulesAfter = true;

    /// <summary>
    ///     Whether the player changed any of the game settings offered by the guide.
    ///     Used to avoid needlessly writing out the client config.
    /// </summary>
    public bool SettingsChanged { get; private set; }

    /// <summary>
    ///     Whether the server rules should be shown once the guide is dismissed.
    /// </summary>
    public bool ShowRulesAfter
    {
        get => _showRulesAfter;
        set
        {
            _showRulesAfter = value;
            if (_pageIndex == _pages.Count - 1)
                UpdateNextButton();
        }
    }

    public event Action? OnClosed;

    public NewPlayerGuidePopup()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TitleLabel.Text = Loc.GetString("new-player-guide-title");
        SubtitleLabel.Text = Loc.GetString("new-player-guide-subtitle");

        BuildPages();

        SkipButton.OnPressed += _ => OnClosed?.Invoke();
        BackButton.OnPressed += _ => ShowPage(_pageIndex - 1);
        NextButton.OnPressed += _ => OnNextPressed();

        ShowPage(0);
    }

    private void OnNextPressed()
    {
        if (_pageIndex == _pages.Count - 1)
        {
            OnClosed?.Invoke();
            return;
        }

        ShowPage(_pageIndex + 1);
    }

    private void ShowPage(int index)
    {
        if (index < 0 || index >= _pages.Count)
            return;

        _pageIndex = index;

        for (var i = 0; i < _pages.Count; i++)
            _pages[i].Visible = i == index;

        PageCounterLabel.Text = Loc.GetString("new-player-guide-page-counter",
            ("current", index + 1),
            ("total", _pages.Count));

        BackButton.Disabled = index == 0;
        SkipButton.Visible = index != _pages.Count - 1;
        UpdateNextButton();

        Scroll.SetScrollValue(default);
    }

    private void UpdateNextButton()
    {
        var isLastPage = _pageIndex == _pages.Count - 1;

        NextButton.Text = Loc.GetString(!isLastPage
            ? "new-player-guide-next"
            : _showRulesAfter
                ? "new-player-guide-finish"
                : "new-player-guide-close");
    }

    private void AddPage(Control page)
    {
        page.Visible = false;
        page.HorizontalExpand = true;
        _pages.Add(page);
        PageContainer.AddChild(page);
    }

    private void SetSetting<T>(CVarDef<T> cvar, T value) where T : notnull
    {
        _cfg.SetCVar(cvar, value);
        SettingsChanged = true;
    }

    private static BoxContainer BuildPage(string titleKey, string bodyKey, Control? content = null)
    {
        var page = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        page.AddChild(new Label
        {
            Text = Loc.GetString(titleKey),
            StyleClasses = { StyleClass.LabelHeading },
        });

        page.AddChild(new RichTextLabel
        {
            Text = Loc.GetString(bodyKey),
            HorizontalExpand = true,
        });

        if (content == null)
            return page;

        content.Margin = new Thickness(0, 8, 0, 0);
        page.AddChild(content);
        return page;
    }

    private static PanelContainer BuildCard(Control content, MouseFilterMode mouseFilter = MouseFilterMode.Ignore)
    {
        var inner = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 8, 10, 8),
        };
        inner.AddChild(content);

        var card = new PanelContainer
        {
            HorizontalExpand = true,
            MouseFilter = mouseFilter,
            StyleClasses = { StyleClass.BackgroundPanel },
        };
        card.AddChild(inner);
        return card;
    }

    private static readonly Color SelectedCardModulate =
        ReserveRedStylesheet.SecondaryPalette.Background.OkBlend(ReserveRedStylesheet.HighlightPalette.Base, 0.35f);

    private sealed record ChoiceOption(Button Button, string DescriptionKey, Action OnSelected);

    /// <summary>
    ///     Builds a mutually exclusive choice descriptor pairing its toggle button with its description and callback.
    /// </summary>
    private static ChoiceOption BuildChoiceOption(string titleKey, string descriptionKey, Action onSelected)
    {
        var button = new Button
        {
            Text = Loc.GetString(titleKey),
            ToggleMode = true,
            MinHeight = 42,
            HorizontalExpand = true,
        };

        return new ChoiceOption(button, descriptionKey, onSelected);
    }

    /// <summary>
    ///     Lays out two mutually exclusive choice cards in equal-width columns so wide descriptions wrap cleanly.
    /// </summary>
    private static Control BuildChoiceRow(
        ChoiceOption first,
        ChoiceOption second,
        bool firstSelected)
    {
        var group = new ButtonGroup(isNoneSetAllowed: false);
        first.Button.Group = group;
        second.Button.Group = group;

        if (firstSelected)
            first.Button.Pressed = true;
        else
            second.Button.Pressed = true;

        var firstCard = BuildChoiceCard(first.Button, first.DescriptionKey);
        var secondCard = BuildChoiceCard(second.Button, second.DescriptionKey);

        void UpdateCardSelection()
        {
            firstCard.ModulateSelfOverride = first.Button.Pressed ? SelectedCardModulate : null;
            secondCard.ModulateSelfOverride = second.Button.Pressed ? SelectedCardModulate : null;
        }

        void SelectOption(ChoiceOption option)
        {
            UpdateCardSelection();
            option.OnSelected();
        }

        void WireChoice(ChoiceOption option, PanelContainer card)
        {
            option.Button.OnToggled += args =>
            {
                if (args.Pressed)
                    SelectOption(option);
                else
                    UpdateCardSelection();
            };

            card.OnKeyBindDown += args =>
            {
                if (args.Function != EngineKeyFunctions.UIClick || option.Button.Disabled)
                    return;

                if (!option.Button.Pressed)
                {
                    option.Button.SetClickPressed(true);
                    SelectOption(option);
                }

                args.Handle();
            };
        }

        UpdateCardSelection();
        WireChoice(first, firstCard);
        WireChoice(second, secondCard);

        var row = new EqualColumnsContainer
        {
            HorizontalExpand = true,
            Separation = 8,
        };

        row.AddChild(firstCard);
        row.AddChild(secondCard);
        return row;
    }

    private static PanelContainer BuildChoiceCard(Button button, string descriptionKey)
    {
        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        content.AddChild(button);
        content.AddChild(BuildSubTextLabel(descriptionKey));

        return BuildCard(content, MouseFilterMode.Pass);
    }

    private static RichTextLabel BuildSubTextLabel(string textKey)
    {
        var label = new RichTextLabel
        {
            // LabelSheetlet's LabelSubText rule only targets Label (and adding a global RichTextLabel rule
            // would alter existing R&D cards), so use TextSheetlet's FontSmall (10pt) with explicit DarkGray.
            StyleClasses = { StyleClass.FontSmall },
            HorizontalExpand = true,
        };
        label.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString(textKey)), tagsAllowed: null, defaultColor: Color.DarkGray);
        return label;
    }

    private Control BuildSpeechSliders()
    {
        var fontSize = _cfg.GetCVar(GoobCVars.ChatRunechatFontSize);
        var fontSizeSlider = new Slider
        {
            MinValue = RunechatStyle.MinFontSize,
            MaxValue = RunechatStyle.MaxFontSize,
            Value = fontSize,
        };
        var fontSizeValueLabel = new Label
        {
            Text = $"{fontSize}",
        };
        fontSizeSlider.OnValueChanged += args =>
        {
            var val = (int) MathF.Round(args.Value);
            SetSetting(GoobCVars.ChatRunechatFontSize, val);
            fontSizeValueLabel.Text = $"{val}";
            _speechPreview.RefreshFromConfig();
        };

        var outline = _cfg.GetCVar(GoobCVars.ChatRunechatOutlineScale);
        var outlineSlider = new Slider
        {
            MinValue = 0f,
            MaxValue = 2f,
            Value = outline,
        };
        var outlineValueLabel = new Label
        {
            Text = $"{MathF.Round(outline * 100)}%",
        };
        outlineSlider.OnValueChanged += args =>
        {
            SetSetting(GoobCVars.ChatRunechatOutlineScale, args.Value);
            outlineValueLabel.Text = $"{MathF.Round(args.Value * 100)}%";
            _speechPreview.RefreshFromConfig();
        };

        var slidersContainer = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };
        slidersContainer.AddChild(BuildSliderRow(Loc.GetString("ui-options-runechat-font-size"), fontSizeSlider, fontSizeValueLabel));
        slidersContainer.AddChild(BuildSliderRow(Loc.GetString("ui-options-runechat-outline"), outlineSlider, outlineValueLabel));

        return slidersContainer;
    }

    private static Control BuildSliderRow(string title, Slider slider, Label valueLabel)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        row.AddChild(new Label
        {
            Text = title,
            MinWidth = 180,
            VerticalAlignment = VAlignment.Center,
        });

        slider.HorizontalExpand = true;
        slider.VerticalAlignment = VAlignment.Center;
        row.AddChild(slider);

        valueLabel.MinWidth = 48;
        valueLabel.Align = Label.AlignMode.Right;
        valueLabel.VerticalAlignment = VAlignment.Center;
        row.AddChild(valueLabel);

        return row;
    }

    private Control BuildBubblesOptions()
    {
        var container = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        var namesCheckBox = new CheckBox
        {
            Text = Loc.GetString("new-player-guide-speech-bubbles-names"),
            Pressed = _cfg.GetCVar(CCVars.ChatEnableFancyBubbles),
            HorizontalExpand = true,
        };

        var bgCheckBox = new CheckBox
        {
            Text = Loc.GetString("new-player-guide-speech-bubbles-background"),
            Pressed = _cfg.GetCVar(CCVars.ChatFancyNameBackground),
            Disabled = !_cfg.GetCVar(CCVars.ChatEnableFancyBubbles),
            HorizontalExpand = true,
        };

        namesCheckBox.OnToggled += args =>
        {
            SetSetting(CCVars.ChatEnableFancyBubbles, args.Pressed);
            bgCheckBox.Disabled = !args.Pressed;
            _speechPreview.RefreshFromConfig();
        };
        bgCheckBox.OnToggled += args =>
        {
            SetSetting(CCVars.ChatFancyNameBackground, args.Pressed);
            _speechPreview.RefreshFromConfig();
        };

        container.AddChild(namesCheckBox);
        container.AddChild(bgCheckBox);
        return container;
    }

    private static Control BuildMoodInfoCard()
    {
        var container = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        container.AddChild(new Label
        {
            Text = Loc.GetString("new-player-guide-mood-info-title"),
            StyleClasses = { StyleClass.LabelSubText },
        });

        container.AddChild(BuildMoodInfoRow("new-player-guide-mood-info-speed-title", "new-player-guide-mood-info-speed-desc"));
        container.AddChild(BuildMoodInfoRow("new-player-guide-mood-info-visual-title", "new-player-guide-mood-info-visual-desc"));
        container.AddChild(BuildMoodInfoRow("new-player-guide-mood-info-alert-title", "new-player-guide-mood-info-alert-desc"));

        return BuildCard(container);
    }

    private static Control BuildMoodInfoRow(string titleKey, string descKey)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        row.AddChild(new Label
        {
            Text = Loc.GetString(titleKey),
        });

        row.AddChild(BuildSubTextLabel(descKey));

        return row;
    }
}
