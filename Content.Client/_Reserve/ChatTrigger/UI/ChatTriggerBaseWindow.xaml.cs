using Content.Client.UserInterface.Controls;
using Content.Shared.Input;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Analyzers;
using Robust.Shared.Input;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client._Reserve.ChatTrigger.UI;

[GenerateTypedNameReferences]
[Virtual]
public partial class ChatTriggerBaseWindow : FancyWindow
{
    public Action? OnSendAnyway;
    public Action? OnSendWithoutTrigger;
    public Action? OnFix;
    public Action? OnCancel;
    private bool _actionInvoked;

    public ChatTriggerBaseWindow()
    {
        RobustXamlLoader.Load(this);
        CanKeyboardFocus = true;

        CancelButton.OnPressed += _ =>
        {
            _actionInvoked = true;
            var cancel = OnCancel;
            Close();
            cancel?.Invoke();
        };

        FixButton.OnPressed += _ =>
        {
            _actionInvoked = true;
            var fix = OnFix;
            Close();
            fix?.Invoke();
        };

        SendAnywayButton.OnPressed += _ =>
        {
            _actionInvoked = true;
            var send = OnSendAnyway;
            Close();
            send?.Invoke();
        };

        OnClose += () =>
        {
            if (!_actionInvoked)
                OnCancel?.Invoke();

            OnSendAnyway = null;
            OnSendWithoutTrigger = null;
            OnFix = null;
            OnCancel = null;
            _actionInvoked = false;
        };
    }

    protected override void Opened()
    {
        base.Opened();
        _actionInvoked = false;
        GrabKeyboardFocus();
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Handled)
            return;

        if (args.Function == EngineKeyFunctions.TextSubmit ||
            args.Function == EngineKeyFunctions.TextNewline)
        {
            if (FixButton.Visible && !FixButton.Disabled && OnFix != null)
            {
                _actionInvoked = true;
                var fix = OnFix;
                Close();
                fix?.Invoke();
            }
            else if (OnSendWithoutTrigger != null)
            {
                _actionInvoked = true;
                var sendWithout = OnSendWithoutTrigger;
                Close();
                sendWithout?.Invoke();
            }
            else if (SendAnywayButton.Visible && !SendAnywayButton.Disabled && OnSendAnyway != null)
            {
                _actionInvoked = true;
                var send = OnSendAnyway;
                Close();
                send?.Invoke();
            }
            else
            {
                _actionInvoked = true;
                var cancel = OnCancel;
                Close();
                cancel?.Invoke();
            }

            args.Handle();
        }
        else if (args.Function == EngineKeyFunctions.TextReleaseFocus ||
                 args.Function == EngineKeyFunctions.WindowCloseRecent ||
                 args.Function == ContentKeyFunctions.EscapeContext)
        {
            _actionInvoked = true;
            var cancel = OnCancel;
            Close();
            cancel?.Invoke();
            args.Handle();
        }
    }

    public void SetDescription(string description)
    {
        DescriptionLabel.SetMessage(FormattedMessage.FromMarkupPermissive(description));
    }

    public void SetDescription(FormattedMessage description)
    {
        DescriptionLabel.SetMessage(description);
    }

    public void SetMessage(string message)
    {
        MessageLabel.SetMessage(FormattedMessage.FromMarkupPermissive(message));
    }

    public void SetMessage(FormattedMessage message)
    {
        MessageLabel.SetMessage(message);
    }

    public void SetTriggerWord(string? trigger)
    {
        if (string.IsNullOrEmpty(trigger))
        {
            TriggerLabel.Visible = false;
            return;
        }

        var msg = new FormattedMessage();
        msg.AddText(Loc.GetString("chat-trigger-brainrot-trigger-prefix"));
        msg.PushColor(Color.OrangeRed);
        msg.AddText($" «{trigger}»");
        msg.Pop();
        TriggerLabel.SetMessage(msg);
        TriggerLabel.Visible = true;
    }

    public void SetCanFix(bool canFix)
    {
        FixButton.Visible = canFix;
        FixButton.Disabled = !canFix;
    }
}
