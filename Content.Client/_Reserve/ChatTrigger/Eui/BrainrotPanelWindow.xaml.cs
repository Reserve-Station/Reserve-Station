using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Reserve.ChatTrigger;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Reserve.ChatTrigger.Eui;

[GenerateTypedNameReferences]
public sealed partial class BrainrotPanelWindow : FancyWindow
{
    private readonly BrainrotPanelEui _eui;

    public BrainrotPanelWindow(BrainrotPanelEui eui)
    {
        _eui = eui;
        RobustXamlLoader.Load(this);

        AddBtn.OnPressed += _ => SendAddMsg();
        AddInput.OnTextEntered += _ => SendAddMsg();
        AddInput.OnTextChanged += _ => ClearError();
    }

    private void ClearError()
    {
        ErrorLabel.Visible = false;
        ErrorLabel.Text = string.Empty;
        ErrorLabel.ToolTip = null;
        AddInput.ToolTip = null;
    }

    private void SendAddMsg()
    {
        var text = AddInput.Text.Trim();
        if (string.IsNullOrEmpty(text))
            return;

        if (!ChatTriggerHelper.IsValidTrigger(text, out var error))
        {
            ErrorLabel.Text = error;
            ErrorLabel.Visible = true;
            ErrorLabel.ToolTip = error;
            AddInput.ToolTip = error;
            return;
        }

        ClearError();
        _eui.AddTrigger(text);
        AddInput.Text = string.Empty;
    }

    public void UpdateState(BrainrotPanelEuiState state)
    {
        TriggersContainer.DisposeAllChildren();

        foreach (var trigger in state.CustomTriggers.OrderBy(t => t, StringComparer.OrdinalIgnoreCase))
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                HorizontalExpand = true
            };

            var label = new Label
            {
                Text = trigger,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                ClipText = true,
                ToolTip = trigger
            };

            var deleteBtn = new Button
            {
                Text = Loc.GetString("brainrot-panel-delete"),
                VerticalAlignment = VAlignment.Center
            };

            var confirming = false;
            deleteBtn.OnPressed += _ =>
            {
                if (!confirming)
                {
                    confirming = true;
                    deleteBtn.Text = Loc.GetString("brainrot-panel-delete-confirm");
                    deleteBtn.Modulate = Color.FromHex("#FF6666");
                }
                else
                {
                    _eui.RemoveTrigger(trigger);
                }
            };

            row.AddChild(label);
            row.AddChild(deleteBtn);

            TriggersContainer.AddChild(row);
        }
    }
}
